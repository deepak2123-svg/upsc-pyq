import {expect,test} from '@playwright/test';

test('compact setup keeps sources explicit, validates timing and starts the selected online test',async({page})=>{
 await page.goto('/');
 const browser=page.locator('.scope-library-browser');
 await browser.getByRole('button',{name:'Add to test: Geography',exact:true}).click();
 await page.locator('.scope-test-summary').getByRole('button',{name:'Finalise test →',exact:true}).click();
 const dialog=page.getByRole('dialog',{name:'Finalise test',exact:true});
 await expect(dialog).toBeVisible();
 expect((await dialog.boundingBox())!.width).toBeLessThanOrEqual(521);
 const sources=dialog.locator('.compact-source');
 await expect(sources).toHaveCount(4);
 const cse=sources.filter({hasText:'CSE'});
 await expect(cse).toHaveAttribute('aria-pressed','true');
 const enabledBackground=await cse.evaluate(el=>getComputedStyle(el).backgroundColor);
 await cse.click();
 await expect(cse).toContainText('Excluded');
 expect(await cse.evaluate(el=>getComputedStyle(el).filter)).toBe('grayscale(1)');
 expect(await cse.evaluate(el=>getComputedStyle(el).backgroundColor)).not.toBe(enabledBackground);
 for(const exam of ['CAPF','CDS','NDA'])await sources.filter({hasText:exam}).click();
 await expect(dialog.getByRole('button',{name:'Start test →',exact:true})).toBeDisabled();
 await cse.click();
 await dialog.getByRole('group',{name:'Questions',exact:true}).getByRole('button',{name:'10',exact:true}).click();
 await dialog.getByLabel('Time limit',{exact:true}).selectOption('custom');
 await dialog.getByLabel('Custom minutes',{exact:true}).fill('0');
 await expect(dialog.getByRole('button',{name:'Start test →',exact:true})).toBeDisabled();
 await dialog.getByLabel('Custom minutes',{exact:true}).fill('15');
 await dialog.getByRole('button',{name:'Offline - PDF paper',exact:true}).click();
 await dialog.getByLabel('Answer key',{exact:true}).selectOption('yes');
 await dialog.getByRole('button',{name:'Online test',exact:true}).click();
 await page.screenshot({path:'tmp/compact-setup-desktop.png'});
 await page.setViewportSize({width:390,height:844});
 expect(await dialog.evaluate(el=>el.scrollWidth<=el.clientWidth)).toBe(true);
 await page.screenshot({path:'tmp/compact-setup-mobile.png'});
 const created=page.waitForResponse(r=>r.url().endsWith('/api/practice-snapshots')&&r.request().method()==='POST');
 await dialog.getByRole('button',{name:'Start test →',exact:true}).click();
 const snapshot=await(await created).json();
 expect(snapshot.questions).toHaveLength(10);
 expect(snapshot.questions.every((q:{exam:string})=>q.exam==='CSE')).toBe(true);
 expect(snapshot.recipe.durationMinutes).toBe(15);
 await expect(page.locator('.question-heading')).toContainText('Question 1 of 10');
});
